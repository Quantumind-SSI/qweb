#!/usr/bin/env python3
"""
Hoist CSS rules that are duplicated across pages into a single shared
stylesheet (css/patterns.css) and delete them from the pages.

The previous build copy-pasted the same component CSS (.pillar-card,
.product-card, .stat, .quote, .pillars-grid …) into a dozen separate <style>
blocks. Editing one of them changed one page.

A rule is hoisted when the same selector + the same declaration body appears
in THRESHOLD or more pages. Anything genuinely page-specific stays put.
"""

import re
import sys
import glob
import pathlib
import collections

ROOT = pathlib.Path(__file__).resolve().parent.parent
THRESHOLD = 3
OUT = ROOT / "css" / "patterns.css"


def tokenize(css: str):
    """Yield (prelude, block, raw) for top-level rules; None prelude = trivia."""
    i, n = 0, len(css)
    while i < n:
        if css.startswith("/*", i):
            j = css.find("*/", i + 2)
            j = n if j == -1 else j + 2
            yield None, None, css[i:j]
            i = j
            continue

        if css[i] in " \t\r\n":
            j = i
            while j < n and css[j] in " \t\r\n":
                j += 1
            yield None, None, css[i:j]
            i = j
            continue

        depth, j = 0, i
        while j < n:
            c = css[j]
            if c in "([":
                depth += 1
            elif c in ")]":
                depth -= 1
            elif c in "{;" and depth == 0:
                break
            j += 1

        if j >= n:
            yield None, None, css[i:]
            return

        if css[j] == ";":
            yield css[i:j].strip(), None, css[i:j + 1]
            i = j + 1
            continue

        k, depth = j, 0
        while k < n:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1

        yield css[i:j].strip(), css[j + 1:k], css[i:k + 1]
        i = k + 1


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def rule_key(prelude: str, block: str) -> str:
    return norm(prelude) + "{" + norm(block) + "}"


def collect(pages):
    """rule_key -> (set of pages, pretty text)"""
    seen = collections.defaultdict(lambda: [set(), ""])

    for page in pages:
        css = "\n".join(
            re.findall(r"<style[^>]*>(.*?)</style>", page.read_text(encoding="utf-8"), re.S)
        )
        for prelude, block, raw in tokenize(css):
            if prelude is None or block is None:
                continue
            low = prelude.lower()

            # Media/supports blocks are hoisted whole
            if low.startswith("@media") or low.startswith("@supports") or low.startswith("@keyframes"):
                key = rule_key(prelude, block)
                seen[key][0].add(page.name)
                seen[key][1] = raw.strip()
                continue

            key = rule_key(prelude, block)
            seen[key][0].add(page.name)
            seen[key][1] = raw.strip()

    return seen


def main():
    pages = sorted(p for p in ROOT.glob("*.html"))
    seen = collect(pages)

    shared = {k: v for k, v in seen.items() if len(v[0]) >= THRESHOLD}
    if not shared:
        print("nothing to hoist")
        return

    # Emit shared stylesheet
    header = f"""/* ============================================================================
   QUANTUMINDSSI — SHARED PAGE PATTERNS  (generated by tools/dedupe.py)

   These component rules appeared identically in {THRESHOLD}+ pages of the
   previous build, copy-pasted into separate <style> blocks. They now exist
   once. Editing a rule here changes every page that uses it.

   Values resolve through css/compat.css, so this inherits the corrected
   palette rather than the old one.

   Do not hand-edit: regenerate with `python3 tools/dedupe.py`, or promote a
   rule into css/components.css and delete it from here.
   ========================================================================= */

"""
    body = "\n\n".join(v[1] for v in sorted(shared.values(), key=lambda x: x[1]))
    OUT.write_text(header + body + "\n", encoding="utf-8")

    hoisted_lines = body.count("\n") + 1
    print(f"hoisted {len(shared)} rules -> css/patterns.css ({hoisted_lines} lines)")

    # Strip them from every page
    for page in pages:
        text = page.read_text(encoding="utf-8")
        blocks = re.findall(r"<style[^>]*>(.*?)</style>", text, re.S)
        if not blocks:
            continue

        removed = 0
        kept_all = []
        for css in blocks:
            out = []
            for prelude, block, raw in tokenize(css):
                if prelude is not None and block is not None and rule_key(prelude, block) in shared:
                    removed += 1
                    continue
                out.append(raw)
            kept_all.append("".join(out))

        kept = "\n".join(kept_all)
        kept = re.sub(r"\n{3,}", "\n\n", kept).strip()

        idx = [0]

        def replace(_m):
            idx[0] += 1
            if idx[0] > 1:
                return ""
            if not kept:
                return ""
            return (
                "<style>\n"
                "  /* Page-specific styles. Shared patterns live in css/patterns.css. */\n"
                + kept + "\n  </style>"
            )

        text = re.sub(r"<style[^>]*>.*?</style>", replace, text, flags=re.S)
        text = re.sub(r"\n{3,}", "\n\n", text)
        page.write_text(text, encoding="utf-8")

        if removed:
            print(f"  {page.name:28} -{removed} duplicated rules")

    # Wire the stylesheet into every page
    link = '  <link rel="stylesheet" href="css/patterns.css">'
    for page in pages:
        text = page.read_text(encoding="utf-8")
        if "css/patterns.css" in text:
            continue
        text = text.replace(
            '  <link rel="stylesheet" href="css/compat.css">',
            '  <link rel="stylesheet" href="css/compat.css">\n' + link,
            1,
        )
        page.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
